//! Regenerates `src/bindings.ts` from the Rust command signatures.
//!
//! ```text
//! cargo run --features dev-tools --bin export_bindings
//! ```
//!
//! A binary rather than a test on purpose. `collect_commands!` expands to
//! `tauri::generate_handler!`, which pins the runtime to `Wry`, and linking Wry
//! into a *test* binary yields an executable that dies on startup with
//! STATUS_ENTRYPOINT_NOT_FOUND before any test runs. Ordinary binaries link it
//! exactly the way the real app does, so they are unaffected.
//!
//! CI runs this and then fails if the working tree is dirty, which is what
//! actually keeps the TypeScript from drifting away from the Rust.

use specta_typescript::Typescript;

fn main() {
    // Resolved against the crate, not the working directory.
    //
    // A bare "../src/bindings.ts" is relative to wherever the binary was
    // launched from, and `cargo run --manifest-path …` launches it from the
    // caller's directory — so it wrote a stray `bindings.ts` into the parent of
    // the *repo*, reported success, and left the real one stale. The generated
    // types then silently lagged the Rust, which is the exact drift this binary
    // exists to prevent.
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");

    sourcelight_lib::specta_builder()
        // `ScanProgress` is an event payload, not a command return type, so
        // nothing in the command surface references it and it would otherwise
        // be left out — and then hand-mirrored in TypeScript, which is the
        // exact drift this whole exercise exists to prevent.
        .typ::<sourcelight_lib::models::ScanProgress>()
        // The phone link's event payload, likewise.
        .typ::<sourcelight_lib::phone_link::PhonePairRequest>()
        .typ::<sourcelight_lib::phone_link::PhoneTrack>()
        .export(
            Typescript::default().header(
                "// Generated by tauri-specta from the Rust command signatures.\n\
                 // Do not edit — run `cargo run --features dev-tools --bin export_bindings` to regenerate.\n",
            ),
            path,
        )
        .expect("failed to export TypeScript bindings");

    println!("wrote {path}");
}
