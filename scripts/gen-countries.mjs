// Regenerates src/lib/countryCodes.ts from the core's country table.
//   node scripts/gen-countries.mjs
import fs from "node:fs";

const tsv = fs.readFileSync("src-tauri/resources/geo/countries.tsv", "utf8");
const rows = tsv
  .split(/\r?\n/)
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => l.split("\t"))
  .filter((c) => c.length >= 2 && /^[A-Z]{2}$/.test(c[0]))
  .sort((a, b) => a[1].localeCompare(b[1], "en"));

const body = rows.map(([code, name]) => `  ${JSON.stringify(name)}: ${JSON.stringify(code)},`).join("\n");
const out = `// GENERATED by scripts/gen-countries.mjs from src-tauri/resources/geo/countries.tsv
// (GeoNames countryInfo, CC BY 4.0). Do not edit by hand; re-run the script.
// English country name, as the core sends it, to ISO 3166-1 alpha-2.

export const COUNTRY_CODES: Readonly<Record<string, string>> = {
${body}
};
`;
fs.writeFileSync("src/lib/countryCodes.ts", out);
